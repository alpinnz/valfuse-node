import { lstat, mkdir, readFile, readdir, unlink, writeFile } from "node:fs/promises";
import { basename, dirname, extname, relative, resolve } from "node:path";
import type {
  BarrelGeneratorConfig,
  BarrelGeneratorConfigInput,
  GenerateBarrelOptions,
  GenerateBarrelOutput,
  GenerateBarrelResult,
} from "./types";

interface NormalizedBarrelGeneratorConfig extends BarrelGeneratorConfig {
  recursive: boolean;
}

export const DEFAULT_BARREL_GENERATOR_CONFIG: Readonly<NormalizedBarrelGeneratorConfig> =
  Object.freeze({
    inputDir: "src",
    outputFile: "src/index.ts",
    include: Object.freeze([]),
    exclude: Object.freeze([]),
    recursive: false,
  });

const SOURCE_EXTENSIONS = new Set([".ts", ".tsx"]);
const DEFAULT_EXCLUDED_FILE = /(?:\.test|\.spec|\.stories)\.(?:ts|tsx)$/;
const GENERATED_HEADER = "/**\n * Generated by @valfuse-node/barrel. Do not edit manually.\n */";
const EXCLUDED_DIRECTORIES = new Set([
  "__mocks__",
  "__tests__",
  "build",
  "coverage",
  "dist",
  "node_modules",
  "stories",
  "test",
  "tests",
]);

/** Generate deterministic TypeScript barrels from selected source directories. */
export async function generateBarrel(
  options: GenerateBarrelOptions = {}
): Promise<GenerateBarrelResult> {
  const cwd = resolve(options.cwd ?? process.cwd());
  const config = normalizeConfig(options.config);
  const inputDir = resolve(cwd, config.inputDir);
  const outputFile = resolve(cwd, config.outputFile);

  if (config.recursive && !pathsEqual(dirname(outputFile), inputDir)) {
    throw new Error(
      'Recursive "outputFile" must be named index.ts directly inside configured "inputDir".'
    );
  }

  let inputStats;
  try {
    inputStats = await lstat(inputDir);
  } catch (error) {
    if (isNodeError(error) && error.code === "ENOENT") {
      throw new Error("Barrel input directory not found: " + inputDir, { cause: error });
    }
    throw error;
  }

  if (!inputStats.isDirectory()) {
    throw new Error("Barrel input must be a directory and cannot be a symlink: " + inputDir);
  }

  const sourceDirectories = await collectSourceDirectories(inputDir, config.recursive);
  const pendingOutputs: Array<GenerateBarrelOutput & { source: string }> = [];

  for (const sourceDirectory of sourceDirectories) {
    const directoryOutput = getDirectoryOutput(inputDir, sourceDirectory, outputFile);
    const modules = await collectModules(
      sourceDirectory,
      directoryOutput,
      config,
      pathsEqual(sourceDirectory, inputDir)
    );
    if (modules.length === 0) continue;

    const source = renderBarrel(modules, directoryOutput);
    const existingSource = await readExistingFile(directoryOutput);
    const changed = existingSource !== source;

    if (config.recursive && existingSource !== undefined && !isGeneratedBarrel(existingSource)) {
      throw new Error(
        "Recursive barrel output already exists and is not generator-owned: " + directoryOutput
      );
    }

    pendingOutputs.push({
      outputFile: directoryOutput,
      moduleCount: modules.length,
      changed,
      source,
    });
  }

  const expectedOutputs = pendingOutputs.map((output) => output.outputFile);
  const staleOutputs = config.recursive
    ? await findStaleOutputs(sourceDirectories, inputDir, outputFile, expectedOutputs)
    : [];

  if (options.check) {
    const outdatedOutput = pendingOutputs.find((output) => output.changed);
    if (outdatedOutput) {
      throw new Error(
        "Generated barrel is missing or out of date: " +
          relative(cwd, outdatedOutput.outputFile) +
          '. Run "npx valfuse-barrel" to regenerate it.'
      );
    }
  }

  if (options.check && staleOutputs.length > 0) {
    throw new Error(
      "Generated barrel is stale because its directory has no selected modules: " +
        relative(cwd, staleOutputs[0]) +
        '. Run "npx valfuse-barrel" to remove stale generated files.'
    );
  }

  if (pendingOutputs.length === 0 && staleOutputs.length === 0) {
    throw new Error(
      "No TypeScript modules found in " +
        relative(cwd, inputDir) +
        '. Add eligible .ts/.tsx modules or configure "include".'
    );
  }

  if (!options.check) {
    for (const output of pendingOutputs) {
      if (!output.changed) continue;
      await mkdir(dirname(output.outputFile), { recursive: true });
      await writeFile(output.outputFile, output.source, "utf8");
    }
    for (const staleOutput of staleOutputs) await unlink(staleOutput);
  }

  const outputs = pendingOutputs.map((output) => ({
    outputFile: output.outputFile,
    moduleCount: output.moduleCount,
    changed: output.changed,
  }));
  const outputFiles = outputs.map((output) => output.outputFile);
  const firstOutput = outputFiles[0] ?? staleOutputs[0] ?? outputFile;
  const changed = outputs.some((output) => output.changed) || staleOutputs.length > 0;

  return {
    moduleCount: outputs.reduce((count, output) => count + output.moduleCount, 0),
    outputFile: firstOutput,
    changed,
    ...(config.recursive ? { outputFiles: outputs } : {}),
    ...(staleOutputs.length > 0 && !options.check ? { removedFiles: staleOutputs } : {}),
  };
}

function normalizeConfig(input: BarrelGeneratorConfigInput = {}): NormalizedBarrelGeneratorConfig {
  const include = input.include ?? DEFAULT_BARREL_GENERATOR_CONFIG.include;
  const exclude = input.exclude ?? DEFAULT_BARREL_GENERATOR_CONFIG.exclude;
  const config: NormalizedBarrelGeneratorConfig = {
    ...DEFAULT_BARREL_GENERATOR_CONFIG,
    ...input,
    include: Array.isArray(include) ? [...include] : include,
    exclude: Array.isArray(exclude) ? [...exclude] : exclude,
    recursive: input.recursive ?? DEFAULT_BARREL_GENERATOR_CONFIG.recursive,
  };

  for (const key of ["inputDir", "outputFile"] as const) {
    const value = config[key];
    if (typeof value !== "string" || value.trim() === "") {
      throw new Error('Config "' + key + '" must be a non-empty string.');
    }
  }

  if (typeof config.recursive !== "boolean") {
    throw new Error('Config "recursive" must be a boolean.');
  }

  if (extname(config.outputFile).toLowerCase() !== ".ts") {
    throw new Error('Config "outputFile" must have a .ts extension.');
  }

  if (config.recursive && basename(config.outputFile).toLowerCase() !== "index.ts") {
    throw new Error('Config "outputFile" must be named index.ts when "recursive" is enabled.');
  }

  validateFileNames("include", config.include);
  validateFileNames("exclude", config.exclude);

  const excludedFiles = new Set(config.exclude);
  for (const fileName of config.include) {
    if (excludedFiles.has(fileName)) {
      throw new Error('Module "' + fileName + '" cannot appear in both "include" and "exclude".');
    }
  }

  return config;
}

function validateFileNames(option: "include" | "exclude", fileNames: readonly string[]): void {
  if (!Array.isArray(fileNames)) {
    throw new Error('Config "' + option + '" must be a list of TypeScript file names.');
  }

  const seen = new Set<string>();
  for (const fileName of fileNames) {
    if (
      typeof fileName !== "string" ||
      fileName.trim() === "" ||
      basename(fileName) !== fileName ||
      !SOURCE_EXTENSIONS.has(extname(fileName).toLowerCase()) ||
      !isEligibleModule(fileName)
    ) {
      throw new Error(
        'Config "' + option + '" entries must be eligible .ts/.tsx file names without directories.'
      );
    }
    if (seen.has(fileName))
      throw new Error('Duplicate module "' + fileName + '" in "' + option + '".');
    seen.add(fileName);
  }
}

async function collectModules(
  inputDir: string,
  outputFile: string,
  config: BarrelGeneratorConfig,
  isRootDirectory: boolean
): Promise<string[]> {
  const entries = await readdir(inputDir, { withFileTypes: true });
  entries.sort((left, right) => compareNames(left.name, right.name));

  const availableFiles = entries
    .filter((entry) => entry.isFile() && isEligibleModule(entry.name))
    .map((entry) => entry.name)
    .filter((fileName) => !pathsEqual(resolve(inputDir, fileName), outputFile));
  const availableSet = new Set(availableFiles);

  for (const fileName of config.include) {
    if (isRootDirectory && !availableSet.has(fileName)) {
      throw new Error("Included TypeScript module not found: " + resolve(inputDir, fileName));
    }
  }

  const includedFiles =
    config.include.length > 0
      ? availableFiles.filter((fileName) => config.include.includes(fileName))
      : availableFiles;
  const excludedFiles = new Set(config.exclude);
  return includedFiles
    .filter((fileName) => !excludedFiles.has(fileName))
    .sort(compareNames)
    .map((fileName) => resolve(inputDir, fileName));
}

async function collectSourceDirectories(inputDir: string, recursive: boolean): Promise<string[]> {
  const directories = [inputDir];
  if (!recursive) return directories;

  for (let directoryIndex = 0; directoryIndex < directories.length; directoryIndex += 1) {
    const currentDirectory = directories[directoryIndex];
    if (!currentDirectory) continue;
    const entries = await readdir(currentDirectory, { withFileTypes: true });
    entries.sort((left, right) => compareNames(left.name, right.name));
    for (const entry of entries) {
      if (
        !entry.isDirectory() ||
        entry.name.startsWith(".") ||
        EXCLUDED_DIRECTORIES.has(entry.name.toLowerCase())
      ) {
        continue;
      }

      const childDirectory = resolve(currentDirectory, entry.name);
      directories.push(childDirectory);
    }
  }

  return directories;
}

async function findStaleOutputs(
  sourceDirectories: string[],
  inputDir: string,
  configuredOutput: string,
  expectedOutputs: string[]
): Promise<string[]> {
  const candidateOutputs = sourceDirectories.map((directory) =>
    pathsEqual(directory, inputDir)
      ? configuredOutput
      : resolve(directory, basename(configuredOutput))
  );
  const staleOutputs: string[] = [];

  for (const candidateOutput of candidateOutputs) {
    if (expectedOutputs.some((output) => pathsEqual(output, candidateOutput))) continue;
    const existingSource = await readExistingFile(candidateOutput);
    if (existingSource && isGeneratedBarrel(existingSource)) staleOutputs.push(candidateOutput);
  }

  return staleOutputs;
}

function getDirectoryOutput(inputDir: string, sourceDirectory: string, rootOutput: string): string {
  return pathsEqual(inputDir, sourceDirectory)
    ? rootOutput
    : resolve(sourceDirectory, basename(rootOutput));
}

function isGeneratedBarrel(source: string): boolean {
  return source.startsWith(GENERATED_HEADER);
}

function isEligibleModule(fileName: string): boolean {
  const extension = extname(fileName).toLowerCase();
  return (
    SOURCE_EXTENSIONS.has(extension) &&
    !fileName.startsWith(".") &&
    !/^index\.(?:ts|tsx)$/i.test(fileName) &&
    !/\.d\.ts$/i.test(fileName) &&
    !DEFAULT_EXCLUDED_FILE.test(fileName)
  );
}

function renderBarrel(moduleFiles: string[], outputFile: string): string {
  const outputDirectory = dirname(outputFile);
  const exports = moduleFiles.map((moduleFile) => {
    const relativePath = relative(outputDirectory, moduleFile)
      .replace(/\.(?:ts|tsx)$/i, "")
      .replace(/\\/g, "/");
    const modulePath = relativePath.startsWith(".") ? relativePath : "./" + relativePath;
    return "export * from " + JSON.stringify(modulePath) + ";";
  });

  return [
    "/**",
    " * Generated by @valfuse-node/barrel. Do not edit manually.",
    " */",
    ...exports,
    "",
  ].join("\n");
}

async function readExistingFile(filePath: string): Promise<string | undefined> {
  try {
    return await readFile(filePath, "utf8");
  } catch (error) {
    if (isNodeError(error) && error.code === "ENOENT") return undefined;
    throw error;
  }
}

function pathsEqual(left: string, right: string): boolean {
  const resolvedLeft = resolve(left);
  const resolvedRight = resolve(right);
  return process.platform === "win32"
    ? resolvedLeft.toLowerCase() === resolvedRight.toLowerCase()
    : resolvedLeft === resolvedRight;
}

function compareNames(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

function isNodeError(error: unknown): error is NodeJS.ErrnoException {
  return error instanceof Error && "code" in error;
}
