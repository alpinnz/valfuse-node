import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { mkdtemp, mkdir, readFile, rm, unlink, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { tmpdir } from "node:os";
import { generateBarrel } from "../generator";

describe("generateBarrel", () => {
  let cwd: string;

  beforeEach(async () => {
    cwd = await mkdtemp(resolve(tmpdir(), "valfuse-barrel-"));
  });

  afterEach(async () => {
    await rm(cwd, { recursive: true, force: true });
  });

  async function writeModule(pathFromCwd: string): Promise<void> {
    const filePath = resolve(cwd, pathFromCwd);
    await mkdir(dirname(filePath), { recursive: true });
    await writeFile(filePath, "export {};\n", "utf8");
  }

  function toRelativePaths(filePaths: readonly string[]): string[] {
    return filePaths.map((filePath) => relative(cwd, filePath).split(sep).join("/"));
  }

  it("keeps generation at the input root by default", async () => {
    await writeModule("src/root.ts");
    await writeModule("src/features/users/user.ts");

    const result = await generateBarrel({ cwd });

    expect(toRelativePaths([result.outputFile])).toEqual(["src/index.ts"]);
    expect(result.moduleCount).toBe(1);
    expect(result.outputFiles).toBeUndefined();
    await expect(readFile(resolve(cwd, "src/index.ts"), "utf8")).resolves.toContain(
      'export * from "./root";'
    );
    await expect(
      readFile(resolve(cwd, "src/features/users/index.ts"), "utf8")
    ).rejects.toMatchObject({
      code: "ENOENT",
    });
  });

  it("generates deterministic barrels recursively for eligible modules", async () => {
    await writeModule("src/root.ts");
    await writeModule("src/features/users/user.ts");
    await writeModule("src/features/users/schema.ts");
    await writeModule("src/features/users/user.test.ts");
    await writeModule("src/.internal/secret.ts");
    await writeModule("src/node_modules/external/module.ts");

    const result = await generateBarrel({
      cwd,
      config: { inputDir: "src", outputFile: "src/index.ts", recursive: true },
    });

    expect(toRelativePaths(result.outputFiles?.map((output) => output.outputFile) ?? [])).toEqual([
      "src/index.ts",
      "src/features/users/index.ts",
    ]);
    expect(result.moduleCount).toBe(3);
    await expect(readFile(resolve(cwd, "src/features/users/index.ts"), "utf8")).resolves.toBe(
      [
        "/**",
        " * Generated by @valfuse-node/barrel. Do not edit manually.",
        " */",
        'export * from "./schema";',
        'export * from "./user";',
        "",
      ].join("\n")
    );
  });

  it("removes stale generated barrels after their directory has no eligible modules", async () => {
    await writeModule("src/root.ts");
    const nestedModule = resolve(cwd, "src/features/users/user.ts");
    await writeModule("src/features/users/user.ts");

    await generateBarrel({
      cwd,
      config: { inputDir: "src", outputFile: "src/index.ts", recursive: true },
    });
    await unlink(nestedModule);

    const result = await generateBarrel({
      cwd,
      config: { inputDir: "src", outputFile: "src/index.ts", recursive: true },
    });

    expect(toRelativePaths(result.removedFiles ?? [])).toEqual(["src/features/users/index.ts"]);
    await expect(
      readFile(resolve(cwd, "src/features/users/index.ts"), "utf8")
    ).rejects.toMatchObject({
      code: "ENOENT",
    });
  });

  it("does not overwrite handwritten barrels or partially write other outputs", async () => {
    await writeModule("src/root.ts");
    await writeModule("src/features/users/user.ts");
    const handwrittenBarrel = resolve(cwd, "src/features/users/index.ts");
    await mkdir(dirname(handwrittenBarrel), { recursive: true });
    await writeFile(handwrittenBarrel, "// maintained by hand\n", "utf8");

    await expect(
      generateBarrel({
        cwd,
        config: { inputDir: "src", outputFile: "src/index.ts", recursive: true },
      })
    ).rejects.toThrow("not generator-owned");

    await expect(readFile(resolve(cwd, "src/index.ts"), "utf8")).rejects.toMatchObject({
      code: "ENOENT",
    });
    await expect(readFile(handwrittenBarrel, "utf8")).resolves.toBe("// maintained by hand\n");
  });

  it("reports stale output in check mode without modifying it", async () => {
    await writeModule("src/root.ts");
    await generateBarrel({ cwd });
    const rootBarrel = resolve(cwd, "src/index.ts");
    await writeFile(rootBarrel, "// changed\n", "utf8");

    await expect(generateBarrel({ cwd, check: true })).rejects.toThrow("out of date");
    await expect(readFile(rootBarrel, "utf8")).resolves.toBe("// changed\n");
  });
});
